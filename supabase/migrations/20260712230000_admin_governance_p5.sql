create or replace function admin_record_compatibility_observation_p5(
  p_surface text,
  p_domain text,
  p_direction text,
  p_authority text,
  p_outcome text,
  p_count integer default 1
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_count integer := least(10000, greatest(1, coalesce(p_count, 1)));
begin
  if p_surface not in ('admin_command', 'article_lifecycle', 'article_publication', 'public_query', 'vector_search', 'admin_dashboard', 'admin_analytics')
    or p_domain not in ('queue', 'lifecycle', 'publication', 'projection', 'operations')
    or p_direction not in ('read', 'write')
    or p_authority not in ('legacy', 'new', 'fallback')
    or p_outcome not in ('selected', 'succeeded', 'failed', 'fallback', 'skipped', 'disabled', 'unavailable') then
    raise exception 'ADMIN_P5_INVALID_OBSERVATION';
  end if;

  insert into admin_compatibility_observations_p5 (
    bucket_started_at, surface, domain, direction, authority, outcome,
    observation_count, unexplained_count, first_observed_at, last_observed_at
  ) values (
    date_trunc('hour', v_now), p_surface, p_domain, p_direction, p_authority, p_outcome,
    v_count, case when p_authority in ('legacy', 'fallback') then v_count else 0 end, v_now, v_now
  )
  on conflict (bucket_started_at, surface, domain, direction, authority, outcome)
  do update set
    observation_count = least(9223372036854775807, admin_compatibility_observations_p5.observation_count + excluded.observation_count),
    unexplained_count = least(9223372036854775807, admin_compatibility_observations_p5.unexplained_count + excluded.unexplained_count),
    first_observed_at = least(admin_compatibility_observations_p5.first_observed_at, excluded.first_observed_at),
    last_observed_at = greatest(admin_compatibility_observations_p5.last_observed_at, excluded.last_observed_at);
end;
$$;

create or replace function admin_record_owner_approval_p5(
  p_role_key text,
  p_actor_hash text,
  p_evidence_digest text,
  p_expires_at timestamptz
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id bigint;
begin
  if p_role_key not in ('operations', 'data', 'security')
    or p_actor_hash !~ '^[0-9a-f]{64}$'
    or p_evidence_digest !~ '^[0-9a-f]{64}$'
    or p_expires_at <= now()
    or p_expires_at > now() + interval '180 days' then
    raise exception 'ADMIN_P5_INVALID_APPROVAL';
  end if;
  insert into admin_governance_evidence_p5 (
    evidence_type, role_key, outcome, actor_hash, expires_at, evidence_digest, note_code
  ) values ('owner_approval', p_role_key, 'approved', p_actor_hash, p_expires_at, p_evidence_digest, 'retirement.readiness')
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function admin_record_backup_restore_evidence_p5(
