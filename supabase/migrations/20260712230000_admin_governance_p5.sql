create or replace view admin_operational_health_core_p5
with (security_barrier = true)
as
with legacy_public as (
  select id from articles
  where status = 'summarized' and source_metadata #>> '{collection,publishable}' = 'true'
), explicit_public as (
  select id from public_article_projection_p3
), publication_identity as (
  select
    (select count(*) from legacy_public)::bigint as legacy_count,
    (select count(*) from explicit_public)::bigint as explicit_count,
    (select count(*) from (
      (select id from legacy_public except select id from explicit_public)
      union all
      (select id from explicit_public except select id from legacy_public)
    ) mismatch)::bigint as mismatch_count,
    (select md5(count(*)::text || ':' || coalesce(sum(hashtextextended(id::text, 0)::numeric), 0)::text) from legacy_public) as legacy_digest,
    (select md5(count(*)::text || ':' || coalesce(sum(hashtextextended(id::text, 0)::numeric), 0)::text) from explicit_public) as explicit_digest
), queue_states as (
  select coalesce(jsonb_object_agg(status, state_count), '{}'::jsonb) as states
  from (select status, count(*)::bigint as state_count from admin_command_runs group by status) grouped
)
select jsonb_build_object(
  'queue', jsonb_build_object(
    'states', (select states from queue_states),
    'oldestQueuedAgeSeconds', (select extract(epoch from now() - min(created_at))::bigint from admin_command_runs where status = 'queued'),
    'staleLeaseCount', (select count(*)::bigint from admin_command_attempts where status = 'running' and lease_expires_at < now()),
    'oldestHeartbeatAgeSeconds', (select extract(epoch from now() - min(heartbeat_at))::bigint from admin_command_attempts where status = 'running'),
    'abortPendingCount', (select count(*)::bigint from admin_command_runs where abort_requested_at is not null and finished_at is null),
    'oldestAbortAgeSeconds', (select extract(epoch from now() - min(abort_requested_at))::bigint from admin_command_runs where abort_requested_at is not null and finished_at is null),
    'retryWaitingCount', (select count(*)::bigint from admin_command_runs where status = 'retry_wait'),
    'oldestRetryAgeSeconds', (select extract(epoch from now() - min(created_at))::bigint from admin_command_runs where status = 'retry_wait')
  ),
  'lifecycle', jsonb_build_object(
    'backlogCount', (select count(*)::bigint from articles where lifecycle_attention_state in ('active', 'anomaly') or lifecycle_review_state = 'needs_review'),
    'oldestReviewAgeSeconds', (select extract(epoch from now() - min(coalesce(lifecycle_attention_raised_at, lifecycle_review_changed_at)))::bigint from articles where lifecycle_attention_state in ('active', 'anomaly') or lifecycle_review_state = 'needs_review'),
    'unresolvedAnomalyCount', (select count(*)::bigint from article_lifecycle_anomalies_p2 where resolved_at is null)
  ),
  'publication', jsonb_build_object(
    'legacyPublicCount', (select legacy_count from publication_identity),
    'explicitPublicCount', (select explicit_count from publication_identity),
    'parityMismatchCount', (select mismatch_count from publication_identity),
    'quarantineCount', (select count(*)::bigint from article_publication_quarantine_p3),
    'legacyIdentityDigest', (select legacy_digest from publication_identity),
    'explicitIdentityDigest', (select explicit_digest from publication_identity)
  ),
  'outbox', jsonb_build_object(
    'pendingCount', (select count(*)::bigint from article_cache_outbox_p3 where status = 'pending'),
    'processingCount', (select count(*)::bigint from article_cache_outbox_p3 where status = 'processing'),
    'deadLetterCount', (select count(*)::bigint from article_cache_outbox_p3 where status = 'dead_letter'),
    'oldestUndeliveredAgeSeconds', (select extract(epoch from now() - min(created_at))::bigint from article_cache_outbox_p3 where status in ('pending', 'processing'))
  ),
  'inFlight', jsonb_build_object(
    'legacyCount', (select count(*)::bigint from admin_jobs where status in ('queued', 'running', 'cancel_requested')),
    'newCount', (select count(*)::bigint from admin_command_runs where status in ('queued', 'running', 'retry_wait')),
    'conflict', (select exists(select 1 from admin_jobs where status in ('queued', 'running', 'cancel_requested'))) and (select exists(select 1 from admin_command_runs where status in ('queued', 'running', 'retry_wait')))
  )
) as evidence;

create or replace function admin_retention_plan_p5(
  p_command_before timestamptz,
  p_lifecycle_before timestamptz,
  p_publication_before timestamptz,
  p_observation_before timestamptz,
  p_delivered_outbox_before timestamptz,
  p_dead_letter_outbox_before timestamptz
)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select jsonb_build_object(
    'commandAttemptsDue', (select count(*)::bigint from admin_command_attempts where status <> 'running' and finished_at < p_command_before),
    'commandEventsDue', (select count(*)::bigint from admin_command_events e join admin_command_runs r on r.id = e.run_id where r.finished_at < p_command_before),
    'lifecycleEventsDue', (select count(*)::bigint from article_lifecycle_events_p2 where occurred_at < p_lifecycle_before),
    'publicationHistoryDue', (select count(*)::bigint from article_publication_history_p3 where occurred_at < p_publication_before),
    'contentVersionsDue', (select count(*)::bigint from article_content_versions_p3 where created_at < p_publication_before),
    'compatibilityObservationsDue', (select count(*)::bigint from admin_compatibility_observations_p5 where bucket_started_at < p_observation_before),
    'deliveredOutboxDue', (select count(*)::bigint from article_cache_outbox_p3 where status = 'delivered' and delivered_at < p_delivered_outbox_before),
    'deadLetterOutboxDue', (select count(*)::bigint from article_cache_outbox_p3 where status = 'dead_letter' and dead_lettered_at < p_dead_letter_outbox_before),
    'legalHoldActive', exists(select 1 from admin_retention_holds_p5 where released_at is null and starts_at <= now() and (expires_at is null or expires_at > now())),
    'recommendations', jsonb_build_object(
      'commands', 'archive_partition',
      'lifecycle', 'retain_immutable_archive',
      'publication', 'retain_immutable_authority',
      'observations', 'batch_delete_allowed',
      'deliveredOutbox', 'batch_delete_allowed',
      'deadLetterOutbox', 'archive_only'
    )
  );
$$;

create or replace function admin_operational_health_p5(
  p_observation_start timestamptz,
  p_observation_end timestamptz,
  p_command_before timestamptz,
  p_lifecycle_before timestamptz,
  p_publication_before timestamptz,
  p_observation_before timestamptz,
  p_delivered_outbox_before timestamptz,
  p_dead_letter_outbox_before timestamptz
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_core jsonb;
  v_compat jsonb;
  v_sources jsonb;
  v_governance jsonb;
  v_retention jsonb;
begin
  if p_observation_start is null or p_observation_end is null
    or p_observation_start >= p_observation_end
    or p_observation_end > now() + interval '5 minutes'
    or p_observation_end - p_observation_start > interval '90 days' then
    raise exception 'ADMIN_P5_INVALID_WINDOW';
  end if;

  select evidence into v_core from admin_operational_health_core_p5;
  select jsonb_build_object(
    'totalCount', coalesce(sum(observation_count), 0)::bigint,
    'legacyReadCount', coalesce(sum(observation_count) filter (where authority = 'legacy' and direction = 'read'), 0)::bigint,
    'legacyWriteCount', coalesce(sum(observation_count) filter (where authority = 'legacy' and direction = 'write'), 0)::bigint,
    'newReadCount', coalesce(sum(observation_count) filter (where authority = 'new' and direction = 'read'), 0)::bigint,
    'newWriteCount', coalesce(sum(observation_count) filter (where authority = 'new' and direction = 'write'), 0)::bigint,
    'fallbackCount', coalesce(sum(observation_count) filter (where authority = 'fallback'), 0)::bigint,
    'unexplainedLegacyCount', coalesce(sum(unexplained_count), 0)::bigint,
    'firstObservedAt', min(first_observed_at),
    'lastObservedAt', max(last_observed_at),
    'bucketCount', count(*)::bigint
  ) into v_compat
  from admin_compatibility_observations_p5
  where bucket_started_at >= date_trunc('hour', p_observation_start)
    and bucket_started_at <= date_trunc('hour', p_observation_end);

  select coalesce(jsonb_agg(jsonb_build_object(
    'sourceKey', s.source_key,
    'active', s.is_active,
    'latestRunAt', latest.started_at,
    'freshnessAgeSeconds', case when latest.started_at is null then null else extract(epoch from now() - latest.started_at)::bigint end
  ) order by s.source_key), '[]'::jsonb) into v_sources
  from sources s
  left join lateral (
    select r.started_at from ingestion_runs r where r.source_key = s.source_key order by r.started_at desc limit 1
  ) latest on true;

  select jsonb_build_object(
    'backupRestoreAt', (select evidence_at from admin_governance_evidence_p5 where evidence_type = 'backup_restore' and outcome = 'successful' order by evidence_at desc limit 1),
    'backupRestoreExpiresAt', (select expires_at from admin_governance_evidence_p5 where evidence_type = 'backup_restore' and outcome = 'successful' order by evidence_at desc limit 1),
    'approvedRoles', coalesce((select jsonb_agg(role_key order by role_key) from (
      select distinct on (role_key) role_key from admin_governance_evidence_p5
      where evidence_type = 'owner_approval' and outcome = 'approved' and expires_at > now()
      order by role_key, evidence_at desc
    ) approvals), '[]'::jsonb)
  ) into v_governance;

  v_retention := admin_retention_plan_p5(p_command_before, p_lifecycle_before, p_publication_before, p_observation_before, p_delivered_outbox_before, p_dead_letter_outbox_before);
  return jsonb_build_object(
    'schemaVersion', 1,
    'generatedAt', now(),
    'available', true,
    'observationWindow', jsonb_build_object('start', p_observation_start, 'end', p_observation_end),
    'queue', v_core->'queue',
    'lifecycle', v_core->'lifecycle',
    'publication', v_core->'publication',
    'outbox', v_core->'outbox',
    'sources', v_sources,
    'compatibility', v_compat,
    'inFlight', v_core->'inFlight',
    'governance', v_governance,
    'retention', v_retention - 'recommendations'
  );
end;
$$;

create or replace function admin_apply_retention_p5(
  p_observation_before timestamptz,
  p_delivered_outbox_before timestamptz,
  p_batch_size integer,
  p_confirmation text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_batch integer := least(500, greatest(1, coalesce(p_batch_size, 250)));
  v_observations integer := 0;
  v_outbox integer := 0;
begin
  if p_confirmation <> 'APPLY P5 RETENTION' then
    raise exception 'ADMIN_P5_CONFIRMATION_REQUIRED';
  end if;
  if p_observation_before > now() - interval '180 days' or p_delivered_outbox_before > now() - interval '90 days' then
    raise exception 'ADMIN_P5_RETENTION_MINIMUM';
  end if;
  if exists(select 1 from admin_retention_holds_p5 where released_at is null and starts_at <= now() and (expires_at is null or expires_at > now()) and domain in ('all', 'observations', 'outbox')) then
    raise exception 'ADMIN_P5_LEGAL_HOLD';
  end if;

  with target as (
    select ctid from admin_compatibility_observations_p5 where bucket_started_at < p_observation_before order by bucket_started_at limit v_batch
  ), deleted as (
    delete from admin_compatibility_observations_p5 where ctid in (select ctid from target) returning 1
  ) select count(*) into v_observations from deleted;

  with target as (
    select id from article_cache_outbox_p3 where status = 'delivered' and delivered_at < p_delivered_outbox_before order by delivered_at, id limit v_batch
  ), deleted as (
    delete from article_cache_outbox_p3 where id in (select id from target) and status = 'delivered' returning 1
  ) select count(*) into v_outbox from deleted;

  return jsonb_build_object(
    'compatibilityObservationsDeleted', v_observations,
    'deliveredOutboxDeleted', v_outbox,
    'batchSize', v_batch,
    'authoritativeHistoryDeleted', 0,
    'deadLettersDeleted', 0
  );
end;
$$;

