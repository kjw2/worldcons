-- P5 operational governance. Additive and rerunnable; no legacy authority is removed.

create table if not exists admin_compatibility_observations_p5 (
  bucket_started_at timestamptz not null,
  surface text not null,
  domain text not null,
  direction text not null,
  authority text not null,
  outcome text not null,
  observation_count bigint not null default 0,
  unexplained_count bigint not null default 0,
  first_observed_at timestamptz not null default now(),
  last_observed_at timestamptz not null default now(),
  primary key (bucket_started_at, surface, domain, direction, authority, outcome),
  constraint admin_compat_obs_p5_bucket_check check (bucket_started_at = date_trunc('hour', bucket_started_at)),
  constraint admin_compat_obs_p5_surface_check check (surface in ('admin_command', 'article_lifecycle', 'article_publication', 'public_query', 'vector_search', 'admin_dashboard', 'admin_analytics')),
  constraint admin_compat_obs_p5_domain_check check (domain in ('queue', 'lifecycle', 'publication', 'projection', 'operations')),
  constraint admin_compat_obs_p5_direction_check check (direction in ('read', 'write')),
  constraint admin_compat_obs_p5_authority_check check (authority in ('legacy', 'new', 'fallback')),
  constraint admin_compat_obs_p5_outcome_check check (outcome in ('selected', 'succeeded', 'failed', 'fallback', 'skipped', 'disabled', 'unavailable')),
  constraint admin_compat_obs_p5_count_check check (observation_count > 0 and unexplained_count between 0 and observation_count)
);

create table if not exists admin_governance_evidence_p5 (
  id bigint generated by default as identity primary key,
  evidence_type text not null,
  role_key text,
  outcome text not null,
  actor_hash text not null,
  evidence_at timestamptz not null default now(),
  expires_at timestamptz not null,
  evidence_digest text not null,
  note_code text,
  constraint admin_governance_evidence_p5_type_check check (evidence_type in ('owner_approval', 'backup_restore', 'acknowledgement')),
  constraint admin_governance_evidence_p5_role_check check (role_key is null or role_key in ('operations', 'data', 'security', 'backup')),
  constraint admin_governance_evidence_p5_outcome_check check (outcome in ('approved', 'successful', 'acknowledged')),
  constraint admin_governance_evidence_p5_actor_check check (actor_hash ~ '^[0-9a-f]{64}$'),
  constraint admin_governance_evidence_p5_digest_check check (evidence_digest ~ '^[0-9a-f]{64}$'),
  constraint admin_governance_evidence_p5_note_check check (note_code is null or note_code ~ '^[a-z][a-z0-9._-]{0,119}$'),
  constraint admin_governance_evidence_p5_expiry_check check (expires_at > evidence_at)
);

create table if not exists admin_retention_holds_p5 (
  id bigint generated by default as identity primary key,
  domain text not null,
  reason_code text not null,
  starts_at timestamptz not null default now(),
  expires_at timestamptz,
  released_at timestamptz,
  evidence_digest text not null,
  constraint admin_retention_holds_p5_domain_check check (domain in ('all', 'commands', 'lifecycle', 'publication', 'observations', 'outbox')),
  constraint admin_retention_holds_p5_reason_check check (reason_code ~ '^[a-z][a-z0-9._-]{0,119}$'),
  constraint admin_retention_holds_p5_digest_check check (evidence_digest ~ '^[0-9a-f]{64}$'),
  constraint admin_retention_holds_p5_dates_check check (expires_at is null or expires_at > starts_at)
);

